"""Freeze prepared M1 immutable execution inputs. Does not authorize execution."""
from pathlib import Path
import json,hashlib,datetime,sys
N=Path(__file__).resolve().parent
R2=N.parent/'sp1-e-o2-cancel-calibration-r2-20261107'
R4=N.parent/'sp1-e-o2-cancel-m1-r4-host-20261107'
sys.path.insert(0,str(N/'host'))
from review_m1 import required_paths
OLD=N.parent/'sp1-e-o2-cancel-host-20261107'
R3=N.parent/'sp1-e-o2-cancel-r3-readonly-20261107'
def pin(f):
    f=Path(f);return {'path':str(f),'bytes':f.stat().st_size,'sha256':hashlib.sha256(f.read_bytes()).hexdigest()}
def main():
    c=json.loads((N/'CONTRACT.json').read_text());old=json.loads((R4/'EXECUTION_FREEZE.json').read_text())
    files={x['path']:x for x in old['files']}
    for row in files.values():
        if pin(row['path'])!=row:raise ValueError('old frozen input drift '+row['path'])
    for f in N.rglob('*'):
        if not f.is_file() or f.relative_to(N).parts[0] in ['before','review']:continue
        if f.name in ['BEFORE.json','EXECUTION_FREEZE.json'] or '.used.' in f.name:continue
        files[str(f)]=pin(f)
    for f in [R3/'DESIGN_CONTRACT.md',R3/'DESIGN_CONTRACT.json',R3/'VALIDATION_BUDGET.md',R3/'BUDGET_PROPOSAL.json',R2/'CONTRACT.json',R2/'R1_EVIDENCE.json',R2/'RESULT.json',R2/'host/RESULT.json',R2/'host/tests.log',OLD/'host/judge-check-01/RESULT.json',OLD/'host/judge-check-01/1.stdout',OLD/'negative/NORMALIZATION_AUDIT.json',OLD/'software/manifest.json']:
        files[str(f)]=pin(f)
    # Exact original normal/reject log inputs for read-only recheck.
    r1=json.loads((R2/'R1_EVIDENCE.json').read_text())
    for row in r1['files']:files[row['path']]=pin(row['path'])
    for role in ['01-bit100','02-candidate-normal']:
        for name in ['stdout.log','stderr.log','record.json']:
            f=R2/'target-01'/role/name;files[str(f)]=pin(f)
    for x in c['runtime'].values():files[x['path']]=pin(x['path'])
    # Tools and actual direct C include closure, without native execution.
    for depfile in (N/'build-review/attempt-01').glob('*.d'):
        content=depfile.read_text().replace('\\\n',' ')
        for name in content.partition(':')[2].split():
            f=Path(name)
            if f.is_file():files[str(f.resolve())]=pin(f.resolve())
    # Use exactly the reviewer's existing required set, including declared provenance.
    for name in sorted(required_paths()):
        f=Path(name);files[str(f)]=pin(f)
    for name in ['EXECUTION_FREEZE.json','PREP_RESULT.json','host/RESULT.json','external-host/RESULT.json','EVIDENCE_MANIFEST.json','NEXT_STEP.md','build-review/attempt-01/OBJECT_AUDIT.json','negative/RESULT.json']:
        f=R4/name;files[str(f)]=pin(f)
    result={'schema':'o2-cancel-r4-r1-execution-freeze-v1','operation_id':c['operation_id'],'created_utc':datetime.datetime.now(datetime.timezone.utc).isoformat(),'roles':c['roles'],'limits':c['limits'],'files':sorted(files.values(),key=lambda x:x['path']),'target_permission':'NOT_AUTHORIZED_CURRENT_TASK_HOST_ONLY','no_retry':True,'authorization_boundary':'EXECUTION_REQUEST.txt and RUN_AUTHORIZATION.json must be newly supplied on explicit future target instruction, bound by hashes to this freeze, CONTRACT and passing host result. They are not generated by host admission.','prior_freeze':pin(R4/'EXECUTION_FREEZE.json')}
    with (N/'EXECUTION_FREEZE.json').open('x') as f:json.dump(result,f,ensure_ascii=False,indent=2);f.write('\n')
    print('FROZEN_PREPARED_INPUTS',len(files),'TARGET_AUTHORIZED_FALSE')
if __name__=='__main__':main()
