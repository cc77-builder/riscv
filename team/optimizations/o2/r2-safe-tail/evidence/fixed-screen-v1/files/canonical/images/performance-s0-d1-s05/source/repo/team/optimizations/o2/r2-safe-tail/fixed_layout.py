_legacy_validate_controls = f.validate_controls
_bound = False


def generate(repo, output, variant, dataset, shard, suite="smoke"):
    """Keep every original case/body; change only explicit assembly layout."""
    repo, output = Path(repo).resolve(), Path(output)
    g.verify_sources(repo)
    old = g.load("r2_fixed_frozen_candidate", repo / g.REL / "candidate.py")
    value = old.generate(repo, output, variant, dataset, shard, suite)
    asm = (output / "kernels.S").read_text()
    g.require(asm.count(".option norvc\n") == 1 and
              asm.count(".balign 4096\n") == 8 and ".option norelax" not in asm,
              "unexpected original assembly layout")
    asm = asm.replace(".option norvc\n", ".option norvc\n.option norelax\n")
    asm = asm.replace(".balign 4096\n", ".balign 8192\n")
    (output / "kernels.S").write_text(asm)
    # ISA/math and UART contract unchanged; layout has a separate identity.
    value.update(layout_contract=LAYOUT_CONTRACT, kernel_slot_bytes=SLOT,
                 layout_adapter_sha256=g.sha(repo / ADAPTER))
    value["files"] = {name: g.sha(output / name) for name in ("kernels.S", "cases.h")}
    g.save(output / "manifest.json", value)
    return value


def regenerate(build):
    build = Path(build)
    manifest = m.read_json(build / "data/manifest.json")
    snapshot = build / "source/repo"
    g.verify_sources(snapshot)
    g.require((snapshot / ADAPTER).read_bytes() == Path(__file__).read_bytes(),
              "fixed-layout adapter source snapshot differs")
    g.require(manifest.get("layout_contract") == LAYOUT_CONTRACT and
              manifest.get("layout_adapter_sha256") == g.sha(Path(__file__)),
              "wrong layout generator identity")
    with tempfile.TemporaryDirectory(prefix="r2-fixed-regenerate-") as tmp:
        fresh = generate(snapshot, Path(tmp) / "data", manifest["r2_variant"],
                         manifest["dataset"], manifest["shard"], manifest["suite"])
        g.require(fresh == manifest, "fixed-layout exact manifest regeneration differs")
        for name in ("kernels.S", "cases.h"):
            g.require((Path(tmp) / "data" / name).read_bytes() == (build / "data" / name).read_bytes(),
                      "fixed-layout generated bytes differ: " + name)
    for name in ("main.c", "Makefile", "fixed-layout.ld"):
        g.require((build / "source" / name).read_bytes() == (snapshot / g.O3 / name).read_bytes(),
                  "harness/build source drift")
    return manifest


def object_layout(obj):
    g.require(obj.kind == 1 and ".text" in obj.named, "reference must be ET_REL text")
    text = obj.named[".text"]
    g.require(text[5] == 4 * SLOT and text[8] == SLOT, "reference object slots differ")
    g.require(not any(s[1] in (4, 9) and s[5] for s in obj.sections),
              "fixed-layout reference contains relocations")
    for index in range(4):
        address, size, _, info = obj.symbols[f"t13_kernel_{index}"]
        g.require(address == index * SLOT and 0 < size <= SLOT and info & 15 == 2,
                  "reference kernel escapes fixed slot")


def verify_build_commands(build, receipt):
    """Validate original command receipts even after byte-preserving relocation."""
    commands = receipt["commands"]
    tools = receipt["toolchain"]
    g.require(len(commands) == 2 and set(tools) == {"gcc", "ld", "ar", "objcopy", "objdump", "readelf", "make"},
              "build command/tool inventory")
    for name, tool in tools.items():
        g.require(set(tool) == {"path", "sha256"} and PurePosixPath(tool["path"]).is_absolute() and
                  len(tool["sha256"]) == 64 and all(c in "0123456789abcdef" for c in tool["sha256"]),
                  "invalid recorded tool: " + name)
    make = commands[0]["command"]
    g.require(len(make) == 15 and make[1] == "-C", "unexpected make argv shape")
    # The recorded commands ran on Linux, independently of the audit host.
    original = PurePosixPath(make[2]).parent
    g.require(PurePosixPath(make[2]).name == "source" and original.is_absolute() and
              PurePosixPath(receipt["source_root"]).is_absolute(), "build root in argv")
    prefix = tools["gcc"]["path"][:-3]
    expected_make = [tools["make"]["path"], "-C", str(original / "source"),
                     "ARCH=riscv64-xs", "MARCH=rv64gcv", "CROSS_COMPILE=" + prefix,
                     "T13_DATA=" + str(original / "data"), "T13_OBJ_ROOT=" + str(original / "objects"),
                     "BINARY=" + str(original / "vdot-perf"), "-o", "am", "-o", "klib", "-j1", "image"]
    expected_reference = [tools["gcc"]["path"], "-march=rv64gcv", "-mabi=lp64d", "-mno-relax",
                          "-c", str(original / "data/kernels.S"), "-o", str(original / "kernels-reference.o")]
    for step, command, expected in zip(("make-command", "reference-command"), commands,
                                      (expected_make, expected_reference)):
        g.require(command == m.read_json(build / step / "command.json"), "build command receipt differs: " + step)
        g.require(command["command"] == expected and command["cwd"] == receipt["source_root"] and
                  command.get("process_started") is True and type(command.get("pid")) is int and
                  command["pid"] > 0 and command.get("exit_code") == 0 and not command.get("timed_out"),
                  "incomplete or changed build command: " + step)
        start, finish = [datetime.fromisoformat(command[key]) for key in ("started", "finished")]
        g.require(start.utcoffset() is not None and finish.utcoffset() is not None and start <= finish,
                  "invalid build command timestamps")
        g.require(command["raw_sha256"] == {name: g.sha(build / step / name)
                                           for name in ("stdout.log", "stderr.log")},
                  "build command raw logs differ: " + step)
    g.require(datetime.fromisoformat(commands[0]["finished"]) <= datetime.fromisoformat(commands[1]["started"]),
              "reference was not independently compiled after AM link")


def verify_build(build, repo):
    build, repo = Path(build), Path(repo)
    receipt = m.read_json(build / "build.json")
    g.require(receipt.get("kind") == "nexus-am-riscv64-xs" and receipt.get("exit_code") == 0 and
              receipt.get("layout_contract") == LAYOUT_CONTRACT, "not a successful fixed-layout AM build")
    g.require(set(receipt["artifacts"]) ==
              {"vdot-perf.elf", "vdot-perf.bin", "kernels-reference.o", "data/manifest.json"},
              "fixed-layout artifact inventory")
    for path, digest in receipt["artifacts"].items():
        g.require(g.sha(build / path) == digest, "fixed-layout build artifact drift: " + path)
    verify_build_commands(build, receipt)
    manifest = regenerate(build)
    g.require(receipt["selection"] == {key: manifest["r2_variant" if key == "variant" else key]
                                    for key in ("suite", "dataset", "shard", "variant")},
              "fixed-layout build selection differs")
    audit = g.load("r2_fixed_instruction_audit", repo / "team/optimizations/o2/r2-kernel-audit/audit.py")
    result = g.inspect(build / "vdot-perf.elf", build / "vdot-perf.bin",
                       build / "kernels-reference.o", manifest, audit)
    obj = g.ELF((build / "kernels-reference.o").read_bytes())
    object_layout(obj)
    elf = g.ELF((build / "vdot-perf.elf").read_bytes())
    g.require(elf.read(g.RAM + SLOT, 4 * SLOT) == obj.section(obj.named[".text"]),
              "linked complete slots differ from independent object")
    for index in range(4):
        address, size, _, _ = elf.symbols[f"t13_kernel_{index}"]
        g.require(address == g.RAM + (index + 1) * SLOT and 0 < size <= SLOT,
                  "linked kernel escapes fixed slot")
        elf.read(address, SLOT)
    result.update(layout_contract=LAYOUT_CONTRACT, manifest_sha256=g.sha(build / "data/manifest.json"))
    return result


def allocated_layout(elf):
    return {name: (s[1], s[2], s[3], s[5], s[8]) for name, s in elf.named.items() if s[2] & 2}


def compare_pair(a, b, ma, mb, binary_a, binary_b):
    """All loaded bytes fixed except two vdot slots and exact K13 dot counts."""
    g.require(ma["r2_variant"] == "s0" and mb["r2_variant"] == "s2", "pair variant order")
    for key in ("suite", "dataset", "shard", "m", "k", "scope", "plan", "layout_contract",
                "kernel_slot_bytes", "layout_adapter_sha256"):
        g.require(ma[key] == mb[key], "pair manifest identity differs: " + key)
    g.require(ma["layout_contract"] == LAYOUT_CONTRACT and ma["kernel_slot_bytes"] == SLOT,
              "pair is not fixed-layout contract")
    g.require(ma["shard"] in (4, 5, 6, 7) and
              (ma["m"], ma["k"]) == ((16, 64) if ma["shard"] in (4, 5) else (4, 13)),
              "pair shape/shard domain")
    g.require(ma["scope"] == ("core" if ma["shard"] % 2 == 0 else "endtoend"), "pair scope")
    for elf, manifest, binary in ((a, ma, binary_a), (b, mb, binary_b)):
        elf.executable()
        g.compiled_cases(elf, manifest)
        g.require(binary == elf.binary(), "pair ELF/bin mismatch")
        g.require(elf.symbols["cases"][:2] == (g.FIXED[".benchmark_cases"], 4 * CASE_BYTES),
                  "pair case ABI/address")
    g.require(a.entry == b.entry and allocated_layout(a) == allocated_layout(b), "ALLOC layout differs")
    g.require(a.segments == b.segments, "program headers differ")
    g.require(len(binary_a) == len(binary_b), "load image lengths differ")
    g.require(a.symbols["main"][:2] == b.symbols["main"][:2] and
              a.symbol_data("main") == b.symbol_data("main"), "main address/code differs")
    order = (("basic", "vdot"), ("basic", "rvv"), ("reuse", "vdot"), ("reuse", "rvv"))
    g.require(len(ma["rows"]) == len(mb["rows"]) == 4, "four-case pair required")
    masked_a, masked_b = bytearray(binary_a), bytearray(binary_b)
    allowed_metadata = []
    for index, (software, method) in enumerate(order):
        ra, rb = ma["rows"][index], mb["rows"][index]
        g.require((ra["software"], ra["method"]) == (rb["software"], rb["method"]) == (software, method),
                  "case method/software order differs")
        stable_a = {k: v for k, v in ra.items() if k not in ("body", "dots", "r2_variant")}
        stable_b = {k: v for k, v in rb.items() if k not in ("body", "dots", "r2_variant")}
        g.require(stable_a == stable_b, "pair mathematical input/state differs")
        name = f"t13_kernel_{index}"
        address_a, size_a = a.symbols[name][:2]
        address_b, size_b = b.symbols[name][:2]
        g.require(address_a == address_b == g.RAM + (index + 1) * SLOT and
                  0 < size_a <= SLOT and 0 < size_b <= SLOT, "pair kernel slot differs")
        if method == "rvv":
            g.require(ra["body"] == rb["body"] and ra["dots"] == rb["dots"] and
                      a.read(address_a, SLOT) == b.read(address_b, SLOT),
                      "entire RVV slot or source differs")
        elif ma["k"] == 13:
            g.require(ra["dots"] == 4 and rb["dots"] == 8, "unexpected safe-tail dot counts")
            offset = address_a - g.RAM
            masked_a[offset:offset + SLOT] = bytes(SLOT)
            masked_b[offset:offset + SLOT] = bytes(SLOT)
            field = a.symbols["cases"][0] + index * CASE_BYTES + DOTS_OFFSET
            old, new = a.read(field, 4), b.read(field, 4)
            g.require(old == struct.pack("<I", 4) and new == struct.pack("<I", 8),
                      "case dot metadata is not exactly uint32 4->8")
            pos = field - g.RAM
            masked_a[pos:pos + 4] = masked_b[pos:pos + 4] = bytes(4)
            allowed_metadata.append(dict(case=index, address=hex(field), binary_offset=hex(pos),
                                         before=old.hex(), after=new.hex()))
        else:
            g.require(ra["body"] == rb["body"] and ra["dots"] == rb["dots"],
                      "control kernel changed")
    g.require(masked_a == masked_b, "unexpected loaded byte outside vdot slots/exact dot metadata")
    if ma["k"] == 64:
        g.require(binary_a == binary_b and not allowed_metadata, "16x64 complete load image differs")
    return dict(status="FIXED_LAYOUT_PAIR_PASS", shard=ma["shard"], dataset=ma["dataset"],
                suite=ma["suite"], main=hex(a.symbols["main"][0]), kernel_slot_bytes=SLOT,
                allocated_sections=len(allocated_layout(a)), program_headers=len(a.segments),
                exact_metadata_differences=allowed_metadata, whole_image_identical=binary_a == binary_b,
                unchanged_bytes_sha256=hashlib.sha256(masked_a).hexdigest())


def pair_paths(a, b):
    a, b = Path(a), Path(b)
    return compare_pair(g.ELF((a / "vdot-perf.elf").read_bytes()),
                        g.ELF((b / "vdot-perf.elf").read_bytes()),
                        m.read_json(a / "data/manifest.json"), m.read_json(b / "data/manifest.json"),
                        (a / "vdot-perf.bin").read_bytes(), (b / "vdot-perf.bin").read_bytes())


def validate_controls(images, repo):
    _legacy_validate_controls(images, repo)
    by = {(x["suite"], x["dataset"], x["shard"], x["variant"]): x for x in images}
    return [pair_paths(by[(i["suite"], i["dataset"], i["shard"], "s0")]["path"], i["path"])
            for i in images if i["variant"] == "s2"]


def canonical_images(repo, cfg):
    base = Path(cfg["canonical_build"])
    state = m.read_json(base / "state.json")
    g.require(state.get("contract") == CONTRACT and state.get("status") == BUILD_PASS,
              "not a completed fixed-layout build")
    images = m.read_json(base / "images.json")["images"]
    expected = {f.image_name(item): item for item in f.inventory()}
    g.require(len(images) == 26 and {i["name"] for i in images} == set(expected),
              "fixed-layout image inventory differs")
    for item in images:
        g.require(all(item[k] == v for k, v in expected[item["name"]].items()), "image label differs")
        build = Path(item["path"])
        g.require(build.resolve() == (base / "images" / item["name"]).resolve(), "image outside build root")
        m.validate_selection(item, m.read_json(build / "data/manifest.json"), m.read_json(build / "build.json"))
        verify_build(build, repo)
        g.require(g.sha(build / "vdot-perf.bin") == item["image_sha256"], "fixed-layout image digest differs")
    validate_controls(images, repo)
    return images


def checker_files(repo):
    values = _legacy_checker_files(repo)
    values.update({str(repo / rel): g.sha(repo / rel) for rel in (ADAPTER, ENTRY)})
    return values


@contextmanager
def bindings(repo):
    """Scoped single-process adapter, with original functions restored on exit."""
    global _bound
    repo = Path(repo).resolve()
    g.require(not _bound, "nested/concurrent fixed-layout binding is unsupported")
    for name, digest in HELPERS.items():
        g.require(g.sha(repo / g.REL / name) == digest, "legacy helper source drift: " + name)
    for module, rel in ((g, g.REL / "linked_gate.py"), (f, g.REL / "fullcore_screen.py"),
                        (m, g.REL / "merged_screen.py")):
        g.require(Path(module.__file__).resolve() == (repo / rel).resolve(), "helper import outside repo")
    g.require(Path(__file__).resolve() == (repo / ADAPTER).resolve(), "layout adapter outside repo")
    changes = [(g, "regenerate", regenerate), (g, "verify_build", verify_build),
               (f, "validate_controls", validate_controls), (m, "canonical_images", canonical_images),
               (m, "checker_files", checker_files), (m, "CONTRACT", CONTRACT), (m, "PASS", PASS)]
    saved = [(module, key, getattr(module, key)) for module, key, _ in changes]
    _bound = True
    try:
        for module, key, value in changes:
            setattr(module, key, value)
        yield
    finally:
        for module, key, value in reversed(saved):
            setattr(module, key, value)
        _bound = False


def build_one(repo, cfg, out, item, tools):
    repo, out = Path(repo).resolve(), Path(out)
    out.mkdir(parents=True, exist_ok=False)
    snapshot = out / "source/repo"
    for name in list(g.PINNED) + [str(ADAPTER)]:
        target = snapshot / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((repo / name).read_bytes())
    g.verify_sources(snapshot)
    for name in ("main.c", "Makefile", "fixed-layout.ld"):
        shutil.copyfile(snapshot / g.O3 / name, out / "source" / name)
    generate(snapshot, out / "data", item["variant"], item["dataset"], item["shard"], item["suite"])
    am = Path(cfg["am_home"])
    libraries = [am / "am/build/am-riscv64-xs.a", am / "libs/klib/build/klib-riscv64-xs.a"]
    frozen = {str(p): g.sha(p) for p in libraries}
    env = os.environ.copy()
    for name in ("CFLAGS", "CPPFLAGS", "CXXFLAGS", "ASFLAGS", "LDFLAGS", "CC_OPT", "MAKEFLAGS",
                 "MFLAGS", "CC", "AS", "LD", "OBJCOPY", "OBJDUMP", "ARCH", "MARCH", "LIBS", "PREBUILD"):
        env.pop(name, None)
    env.update(AM_HOME=str(am), LINUX_GNU_TOOLCHAIN="1")
    prefix = str(Path(tools["gcc"]))[:-3]
    cmd = [tools["make"], "-C", str(out / "source"), "ARCH=riscv64-xs", "MARCH=rv64gcv",
           "CROSS_COMPILE=" + prefix, "T13_DATA=" + str(out / "data"),
           "T13_OBJ_ROOT=" + str(out / "objects"), "BINARY=" + str(out / "vdot-perf"),
           "-o", "am", "-o", "klib", "-j1", "image"]
    record = dict(kind="nexus-am-riscv64-xs", source_base=g.BASE, layout_contract=LAYOUT_CONTRACT,
                  source_root=str(repo),
                  source_commit=subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=repo, text=True).strip(),
                  selection=item, exit_code=None, am_revision=f.AM_COMMIT,
                  external_files=frozen, commands=[], artifacts={})
    g.save(out / "build.json", record)
    try:
        record["commands"].append(f.command(cmd, repo, out / "make-command", env))
        reference = [tools["gcc"], "-march=rv64gcv", "-mabi=lp64d", "-mno-relax", "-c",
                     str(out / "data/kernels.S"), "-o", str(out / "kernels-reference.o")]
        record["commands"].append(f.command(reference, repo, out / "reference-command", env))
        m.verify_files(frozen)
        record["exit_code"] = 0
        record["artifacts"] = {p: g.sha(out / p) for p in
                               ("vdot-perf.elf", "vdot-perf.bin", "kernels-reference.o", "data/manifest.json")}
        record["toolchain"] = {name: dict(path=p, sha256=g.sha(p)) for name, p in tools.items()}
        g.save(out / "build.json", record)
        g.save(out / "elf-validation.json", verify_build(out, repo))
    except BaseException as exc:
        record.update(error=repr(exc), accepted=False)
        g.save(out / "build.json", record)
        raise
    record["accepted"] = True
    g.save(out / "build.json", record)
    return dict(item, name=f.image_name(item), path=str(out), image_sha256=g.sha(out / "vdot-perf.bin"))
