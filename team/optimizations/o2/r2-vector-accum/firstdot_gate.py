"""Exact firstdot regeneration; reuse unchanged R4 ABI/model/layout checks."""
from __future__ import annotations

import json
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[4]
S1 = Path("team/optimizations/o2/r2-vector-accum")
ENTRY = Path("team/optimizations/o2/r2-select")
sys.path.insert(0, str(ROOT / ENTRY))
import entry_gate as parent
import firstdot_candidate as candidate
from entry_gate import ELF, require, sha, blob, load, save, O3, REL, BASE, PINNED, verify_sources

SOURCES = set(parent.SOURCES) | {str(S1 / name) for name in
    ("firstdot_candidate.py", "firstdot_gate.py", "firstdot_experiment.py")}
ARTIFACTS = parent.ARTIFACTS
PUBLIC_C_ARTIFACTS = parent.PUBLIC_C_ARTIFACTS
FROZEN = {
    str(ENTRY / "entry_gate.py"): "d20e0bd7426ac7a3b56b62d2a9b495b51b9cd6da257e46723eddbbb984de8f11",
    str(ENTRY / "entry_experiment.py"): "417b2d8d0b97b293d7db565bfddb39f111756cd23638ddc62c8117997e069b6e",
    str(S1 / "gate.py"): "ab07b578f5fe2dc7782ef9af64e722e051363d1dfddfcd0f1939efb209346b6d",
    **candidate.PINS,
}


def bind(repo):
    repo = Path(repo).resolve()
    require(ROOT == repo and Path(candidate.__file__).resolve() == repo / S1 / "firstdot_candidate.py",
            "firstdot module roots differ")
    require(Path(parent.__file__).resolve() == repo / ENTRY / "entry_gate.py", "parent gate root")
    for rel, digest in FROZEN.items():
        require(sha(repo / rel) == digest, "frozen firstdot dependency drift: " + rel)
    verify_sources(repo)


def regenerate(build):
    build = Path(build)
    manifest = json.loads((build / "data/manifest.json").read_text())
    receipt = json.loads((build / "build.json").read_text())
    snapshot = build / "source/repo"
    verify_sources(snapshot)
    require(set(receipt["snapshot_files"]) == SOURCES, "firstdot snapshot inventory")
    for rel, digest in receipt["snapshot_files"].items():
        require(sha(snapshot / rel) == digest, "firstdot snapshot drift: " + rel)
    generator = load("firstdot_exact_regenerator", snapshot / S1 / "firstdot_candidate.py")
    with tempfile.TemporaryDirectory(prefix="firstdot-regenerate-") as temp:
        out = Path(temp) / "data"
        fresh = generator.generate(snapshot, out, manifest["r2_variant"], manifest["dataset"],
                                   manifest["shard"], manifest["suite"])
        require(fresh == manifest, "firstdot exact manifest regeneration differs")
        for name in candidate.FILES:
            require((out / name).read_bytes() == (build / "data" / name).read_bytes(),
                    "firstdot generated byte drift: " + name)
    for name in ("main.c", "Makefile", "fixed-layout.ld"):
        require((build / "source" / name).read_bytes() == (snapshot / O3 / name).read_bytes(),
                "frozen harness/build source changed")
    return manifest


def verify_build(build, repo):
    build, repo = Path(build), Path(repo).resolve()
    bind(repo)
    receipt = json.loads((build / "build.json").read_text())
    require(receipt.get("kind") == "nexus-am-riscv64-xs" and receipt.get("exit_code") == 0 and
            receipt.get("contract") == candidate.CONTRACT, "not a successful firstdot AM build")
    require(set(receipt["artifacts"]) == ARTIFACTS, "firstdot artifact inventory")
    for rel in SOURCES:
        require(receipt["snapshot_files"].get(rel) == sha(repo / rel), "firstdot selected source drift: " + rel)
    for name, digest in receipt["artifacts"].items():
        require(sha(build / name) == digest, "firstdot artifact drift: " + name)
    require(set(receipt.get("public_c_link_test", {})) == PUBLIC_C_ARTIFACTS, "firstdot C link inventory")
    for name, digest in receipt["public_c_link_test"].items():
        require(sha(build / name) == digest, "firstdot C link drift: " + name)
    manifest = regenerate(build)
    require(manifest["firstdot_contract"] == candidate.CONTRACT and manifest["contract"] == candidate.HARNESS,
            "firstdot/harness identity")
    require(receipt["selection"] == {k: manifest["r2_variant" if k == "variant" else k]
                                     for k in ("suite", "dataset", "shard", "variant")}, "firstdot selection drift")
    result = parent.inspect(build, manifest, repo)
    result.update(status="FIRSTDOT_LINKED_CALLABLE_MODEL_PASS_NOT_DIFFTEST", contract=candidate.CONTRACT)
    return result


def paired_layout(left, right):
    left, right = Path(left), Path(right)
    l, r = [json.loads((p / "data/manifest.json").read_text()) for p in (left, right)]
    require(l["r2_variant"] == "s1" and r["r2_variant"] == "firstdot", "ordered firstdot pair")
    require(l["firstdot_contract"] == r["firstdot_contract"] == candidate.CONTRACT, "pair contract")
    result = parent.paired_layout(left, right)
    b0, b1 = [(p / "vdot-perf.bin").read_bytes() for p in (left, right)]
    for i, row in enumerate(l["rows"]):
        if row["method"] == "rvv":
            require(b0[8192 * (i + 1):8192 * (i + 2)] == b1[8192 * (i + 1):8192 * (i + 2)],
                    "firstdot changed a complete RVV slot")
    require((left / "data/cases.h").read_bytes() == (right / "data/cases.h").read_bytes(),
            "firstdot paired C inputs differ")
    return dict(result, rvv_slots_identical=True, cases_identical=True)


