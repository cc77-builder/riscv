def bind(repo):
    repo = Path(repo).resolve()
    require(repo == ROOT and Path(candidate.__file__).resolve() == repo / S3 / "runtime_candidate.py",
            "S3 runtime module roots differ")
    require(Path(candidate.host.__file__).resolve() == repo / S3 / "candidate.py", "S3 host module root")
    first.bind(repo)
    candidate.host.bind(repo)
    for rel, digest in FROZEN.items():
        require(sha(repo / rel) == digest, "frozen S3 dependency drift: " + rel)


def regenerate(build):
    build = Path(build)
    manifest = json.loads((build / "data/manifest.json").read_text())
    receipt = json.loads((build / "build.json").read_text())
    snapshot = build / "source/repo"
    verify_sources(snapshot)
    require(set(receipt["snapshot_files"]) == SOURCES, "S3 snapshot inventory")
    for rel, digest in receipt["snapshot_files"].items():
        require(sha(snapshot / rel) == digest, "S3 snapshot drift: " + rel)
    generator = load("s3_exact_regenerator", snapshot / S3 / "runtime_candidate.py")
    with tempfile.TemporaryDirectory(prefix="s3-regenerate-") as temp:
        output = Path(temp) / "data"
        fresh = generator.generate(snapshot, output, manifest["r2_variant"], manifest["dataset"],
                                   manifest["shard"], manifest["suite"])
        require(fresh == manifest, "S3 exact manifest regeneration differs")
        for name in candidate.FILES:
            require((output / name).read_bytes() == (build / "data" / name).read_bytes(),
                    "S3 generated byte drift: " + name)
    for name in ("main.c", "Makefile", "fixed-layout.ld"):
        require((build / "source" / name).read_bytes() == (snapshot / O3 / name).read_bytes(),
                "frozen harness/build source changed")
    return manifest


def verify_build(build, repo):
    build, repo = Path(build), Path(repo).resolve()
    bind(repo)
    receipt = json.loads((build / "build.json").read_text())
    require(receipt.get("kind") == "nexus-am-riscv64-xs" and receipt.get("exit_code") == 0 and
            receipt.get("contract") == candidate.CONTRACT, "not a successful S3 AM build")
    require(set(receipt["artifacts"]) == ARTIFACTS, "S3 artifact inventory")
    for rel in SOURCES:
        require(receipt["snapshot_files"].get(rel) == sha(repo / rel), "S3 selected source drift: " + rel)
    for name, digest in receipt["artifacts"].items():
        require(sha(build / name) == digest, "S3 artifact drift: " + name)
    require(set(receipt.get("public_c_link_test", {})) == PUBLIC_C_ARTIFACTS, "S3 C link inventory")
    for name, digest in receipt["public_c_link_test"].items():
        require(sha(build / name) == digest, "S3 C link drift: " + name)
    manifest = regenerate(build)
    require(manifest["config_reuse_runtime_contract"] == candidate.CONTRACT and
            manifest["config_reuse_contract"] == candidate.host.CONTRACT and
            manifest["contract"] == candidate.HARNESS and manifest["runtime_qualified"] is False,
            "S3 generation/runtime identities")
    require(receipt["selection"] == {k: manifest["r2_variant" if k == "variant" else k]
                                     for k in ("suite", "dataset", "shard", "variant")}, "S3 selection drift")
    result = parent.inspect(build, manifest, repo)
    result.update(status="S3_LINKED_CALLABLE_MODEL_PASS_NOT_DIFFTEST", contract=candidate.CONTRACT)
    return result


def erasure(before, after, proof):
    """Independently check the host certificate against real GNU machine words.

    Same strict predicate as the frozen host check.py; no LLVM build is repeated.
    """
    require(before and after and len(before) % 4 == len(after) % 4 == 0, "fixed-width body")
    left, right = [[w for w, in struct.iter_unpack("<I", raw)] for raw in (before, after)]
    require(all(w & 3 == 3 for w in left + right), "compressed body")
    removed = {r["index"] for r in proof["removed"]}
    require(len(removed) == len(proof["removed"]) and len(left) == proof["original_instructions"] and
            len(right) == proof["candidate_instructions"], "erasure cardinality")
    for i in removed:
        require(type(i) is int and 0 <= i < len(left), "erasure index")
        word = left[i]
        require(word & 127 == 0x57 and (word >> 12) & 7 == 7 and word >> 30 == 3 and
                (word >> 7) & 31 == 0, "erased word is not vsetivli x0")
    kept = [i for i in range(len(left)) if i not in removed]
    require(proof["retained_indices"] == kept and [left[i] for i in kept] == right,
            "retained machine word changed")
    return len(removed)


def paired_layout(left, right):
    left, right = Path(left), Path(right)
    m0, m1 = [json.loads((p / "data/manifest.json").read_text()) for p in (left, right)]
    require(m0["r2_variant"] == "firstdot" and m1["r2_variant"] == "config-reuse", "ordered S3 pair")
    require(m0["config_reuse_runtime_contract"] == m1["config_reuse_runtime_contract"] == candidate.CONTRACT,
            "S3 pair contract")
    result = parent.paired_layout(left, right)
    elfs = [ELF((p / "vdot-perf.elf").read_bytes()) for p in (left, right)]
    bins = [(p / "vdot-perf.bin").read_bytes() for p in (left, right)]
    allowed = bytearray(len(bins[0]))
    rows = []
    for r0, r1 in zip(m0["rows"], m1["rows"]):
        symbol = r0["api_symbol"]
        leaves = [e.symbol_data(symbol) for e in elfs]
        start0, size0 = elfs[0].symbols[symbol][:2]
        start1, size1 = elfs[1].symbols[symbol][:2]
        require(start0 == start1 and size1 <= size0, "S3 public leaf layout")
        offset = start0 - parent.original.RAM
        require(0 <= offset < offset + size0 <= len(allowed), "S3 leaf extent")
        allowed[offset:offset + size0] = b"\1" * size0
        require(leaves[0][:8] == leaves[1][:8] and leaves[0][-4:] == leaves[1][-4:], "S3 ABI differs")
        removed = erasure(leaves[0][8:-4], leaves[1][8:-4], r1["config_reuse_proof"])
        transformed, proof = candidate.host.prune(r1["config_reuse_parent_body"])
        require(proof == r1["config_reuse_proof"] and transformed == r1["body"] and
                r0["body"] == r1["config_reuse_parent_body"], "S3 proof/body association")
        rows.append(dict(symbol=symbol, method=r1["method"], software=r1["software"],
                         removed_configs=removed, baseline_bytes=size0, candidate_bytes=size1,
                         baseline_sha256=hashlib.sha256(leaves[0]).hexdigest(),
                         candidate_sha256=hashlib.sha256(leaves[1]).hexdigest()))
    require(all(a == b for a, b, selected in zip(*bins, allowed) if not selected),
            "S3 loaded bytes outside old leaf extents changed")
    for name in ("cases.h", "gemv.h"):
        require((left / "data" / name).read_bytes() == (right / "data" / name).read_bytes(),
                "S3 paired input/header differs")
    return dict(result, leaf_erasure=rows, old_leaf_extent_only=True, cases_identical=True)


