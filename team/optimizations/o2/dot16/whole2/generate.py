"""Independent whole-register supply variant of the existing dot16 full-Q body.

The five retained dot8/RVV/plain-dot16 functions are regenerated by the pinned
old generator and appended verbatim. Only the new symbol uses whole-two loads.
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import json
import tempfile

OLD = Path('team/optimizations/o2/dot16')
OLD_GENERATOR_SHA = 'ad6de7c872f2695297d91a0ed6cb88cb2d71169c7093cf05ff993b87c419e363'
OLD_SCREEN_SHA = 'c53224cfaeb990fd11f2e71a5201988de00ff86f5a9651083baa89b6c3c81006'
FUSED = Path('team/optimizations/o2/r2-config-reuse/caller/runq-q288/fused')
NAME = 'q288_dot16_whole2'
CONTRACT = 'r3-dot16-whole2-host-v1'
CORE_WORDS = 43
FUNCTION_WORDS = 103
FUNCTION_INSTRUCTIONS = 21090


def need(ok, message):
    if not ok:
        raise ValueError(message)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def load(name, path, pin):
    raw = path.read_bytes()
    need(sha(raw) == pin, 'fixed source ' + str(path))
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    need(sha(path.read_bytes()) == pin, 'source changed during load')
    return module


def old_generator(repo):
    return load('whole2_fixed_dot16_candidate', repo / OLD / 'candidate.py', OLD_GENERATOR_SHA)


def core():
    text = '  vsetivli zero, 16, e8, m1, ta, mu\n'
    text += '  vl2re8.v v14, (a1)\n'
    for first in (0, 4):
        for slot in range(4):
            row = first + slot
            text += f'  addi t6, a2, {row * 32}\n'
            text += f'  vl2re8.v v{16 + 2 * slot}, (t6)\n'
        # Consume both halves before reusing these four W register groups.
        for half in range(2):
            for slot in range(4):
                row = first + slot
                destination = row if half == 0 else 24 + row
                word = 0x0e00000b | (destination << 7)
                word |= ((16 + 2 * slot + half) << 15) | ((14 + half) << 20)
                text += f'  .word 0x{word:08x}\n'
    text += '  vsetivli zero, 4, e32, m1, tu, mu\n'
    for row in range(8):
        text += f'  vadd.vv v{row}, v{row}, v{24 + row}\n'
    need(len(text.splitlines()) == CORE_WORDS, '43-word integer core')
    return text


def generate(repo, out):
    need(not out.exists(), 'fresh generator output')
    old = old_generator(repo)
    original = load('whole2_fixed_fusion', repo / FUSED / 'generate.py', old.FUSED_GEN_SHA)
    public_raw = (repo / old.PUBLIC).read_bytes()
    need(sha(public_raw) == old.PUBLIC_SHA, 'fixed team public source')
    public = public_raw.decode()
    before = original.function(public, 'vdot')
    old_core = original.integer_core(public, 'vdot')
    need(before.count(old_core) == 1 and before.count('  addi a1, a1, 32\n') == 1,
         'unique core replacement and unchanged original X footer')
    after = before.replace(old_core, core()).replace('q288_fused_vdot', NAME)
    after = after.replace('.Ltile_vdot', '.Ltile_dot16_whole2')
    after = after.replace('.Lgroup_vdot', '.Lgroup_dot16_whole2')
    with tempfile.TemporaryDirectory(prefix='whole2-retained-dot16-') as temp:
        generated = Path(temp) / 'source'
        old_result = old.generate(repo, generated)
        retained_raw = (generated / 'dot16.S').read_bytes()
    assembly = retained_raw + after.encode()
    out.mkdir(parents=True)
    (out / 'retained-dot16.S').write_bytes(retained_raw)
    (out / 'whole2.S').write_bytes(assembly)
    result = dict(contract=CONTRACT, candidate=NAME, assembly_sha256=sha(assembly),
                  retained_assembly_sha256=sha(retained_raw),
                  retained=old_result['retained'] + [old_result['candidate']],
                  core_words_expected=CORE_WORDS, group_words_expected=64,
                  function_words_expected=FUNCTION_WORDS,
                  expected_dynamic_function_instructions=FUNCTION_INSTRUCTIONS,
                  expected_dynamic_dot16=5184, expected_dynamic_whole2_loads=2916,
                  x_core_advance=0, x_footer_advance=32,
                  weight_layout_changed=False, target_runtime_qualified=False,
                  performance_qualified=False, new_emu_runs=0)
    (out / 'generation.json').write_text(json.dumps(result, indent=2) + '\n')
    return result


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--repo', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(generate(args.repo.resolve(), args.output.resolve()), indent=2))
