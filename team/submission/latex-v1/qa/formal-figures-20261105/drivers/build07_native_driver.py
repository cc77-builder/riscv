"""Build the reviewed report revision in a new isolated native directory.

This bounded round driver consumes a checked delta and the measured build-06
file inventory. It does not touch either Git worktree or the editable Downloads
handoff. Historical engineering results are inputs, never rerun here.
"""
from pathlib import Path, PurePosixPath
from datetime import datetime, timezone
import argparse
import concurrent.futures
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time
import zipfile

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--stage', type=Path, required=True)
parser.add_argument('--bundle-sha256', required=True)
args = parser.parse_args()
stage = args.stage.resolve()
base = stage / 'build-06/source'
out = stage / 'build-07'
bundle = stage / 'report-formal-visual-delta.zip'
digest = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
assert digest(bundle) == args.bundle_sha256, 'Delta identity mismatch'
assert not out.exists(), 'Output exists: preserve it and inspect before reuse'
os.environ['OMP_NUM_THREADS'] = '1'
os.environ['OPENBLAS_NUM_THREADS'] = '1'
started = datetime.now(timezone.utc).isoformat()
with zipfile.ZipFile(bundle) as archive:
    inventory = json.loads(archive.read('baseline-inventory.json'))
    manifest = json.loads(archive.read('delta-manifest.json'))
    assert manifest['base_build'] == 'build-06'
    assert len({entry['path'] for entry in manifest['files']}) == len(manifest['files'])
    regenerated_ids = {
        'S1-01', 'S1-02', 'S1-06', 'S1-07',
        'S2-01', 'S2-02', 'S2-03', 'S2-04', 'S2-05', 'S2-06', 'S2-07', 'S2-08', 'S2-10',
        'S3-01', 'S3-02', 'S3-03', 'S3-04', 'S3-05', 'S3-06', 'S3-07', 'S3-08', 'S3-09',
    }
    derived_paths = {f'figures/{fid}.pdf' for fid in regenerated_ids} | {
        'figures/diagram-layout.json', 'figures/evidence-20261105/generated-figures.json',
        'sections/stage1.tex', 'sections/stage2.tex', 'sections/stage3.tex',
        'qa/pdf-inspection.json', 'figures/page-map.json',
        'publication-manifest.json', '交付校验.json',
    }
    assert not derived_paths.intersection(entry['path'] for entry in manifest['files']), 'Derived files must be regenerated, not frozen as delta inputs'
    for entry in inventory['files']:
        assert digest(base / entry['path']) == entry['sha256'], ('Baseline changed', entry['path'])
    for entry in manifest['files']:
        rel = PurePosixPath(entry['path'])
        assert not rel.is_absolute() and '..' not in rel.parts, rel
        old = entry['before_sha256']
        assert (digest(base / rel) == old if old else not (base / rel).exists()), ('Delta baseline', str(rel))
        assert hashlib.sha256(archive.read(str(rel))).hexdigest() == entry['after_sha256'], str(rel)
    out.mkdir()
    root = out / 'source'
    shutil.copytree(base, root, ignore=shutil.ignore_patterns('output', '__pycache__'))
    inherited = root / 'qa/inherited-build06-current-metadata'
    inherited.mkdir(parents=True, exist_ok=False)
    previous = []
    for rel in ('qa/pdf-inspection.json', 'figures/page-map.json',
                'publication-manifest.json', '交付校验.json'):
        source = root / rel
        if source.is_file():
            target = inherited / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            previous.append({'path': rel, 'sha256': digest(source)})
            shutil.move(str(source), str(target))
    (inherited / 'README.json').write_text(json.dumps({
        'scope': 'Historical current-position metadata inherited from build-06/source. Individual records retain their own build identity; inheritance does not prove they were generated by build-06 or validate build-07.',
        'files': previous}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    for entry in manifest['files']:
        path = root / entry['path']
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(archive.read(entry['path']))
    (out / 'input-delta-manifest.json').write_bytes(archive.read('delta-manifest.json'))

for generator in ('build_evidence_figures.py', 'build_diagram_layouts.py'):
    subprocess.run([sys.executable, '-X', 'utf8', str(root / 'figures' / generator),
                    '--preview-dir', str(out / 'figure-previews'), '--preview-dpi', '220'], check=True)
# Nine screenshot panels are carried forward unchanged from the verified base.
screens = json.loads((root / 'figures/screenshot-layout.json').read_text(encoding='utf-8'))
assert len(screens['figures']) == 9
for entry in screens['figures']:
    assert digest(root / 'figures' / (entry['id'] + '.pdf')) == entry['sha256'], entry['id']
subprocess.run([sys.executable, '-X', 'utf8', str(root / 'expand_reports.py')], check=True)
for entry in manifest['files']:
    assert digest(root / entry['path']) == entry['after_sha256'], ('Source assembly differed', entry['path'])
freeze = {path.relative_to(root).as_posix(): digest(path) for path in sorted(root.rglob('*'))
          if path.is_file() and '__pycache__' not in path.parts
          and ('qa' not in path.relative_to(root).parts or path.suffix == '.py')}
(out / 'frozen-sources.json').write_text(json.dumps(freeze, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
compiler = Path(r'D:\Programs\texlive\2026\bin\windows\xelatex.exe')
names = {'main': '三阶段技术文档_合订本.pdf', 'stage1': '第一阶段_执行日志与过程文档.pdf',
         'stage2': '第二阶段_设计与基础测试文档.pdf', 'stage3': '第三阶段_协同仿真与性能分析.pdf'}
def build(name):
    start = time.monotonic()
    result = subprocess.run([sys.executable, '-X', 'utf8', str(root / 'build.py'),
                             '--compiler', str(compiler), '--output-dir', str(out / name),
                             '--documents', name], capture_output=True)
    (out / (name + '-driver.log')).write_bytes(result.stdout + result.stderr)
    print(json.dumps({'document': name, 'exit': result.returncode,
                      'seconds': round(time.monotonic() - start, 3)}), flush=True)
    return name, result.returncode
with concurrent.futures.ThreadPoolExecutor(max_workers=2) as pool:
    results = list(pool.map(build, names))
assert all(code == 0 for _, code in results), results
assert all(digest(root / key) == value for key, value in freeze.items()), 'Frozen report input changed'
assert all(digest(base / entry['path']) == entry['sha256'] for entry in inventory['files']), 'Base changed during build'
delivery = out / 'delivery'
delivery.mkdir()
files = []
for key, name in names.items():
    path = delivery / name
    shutil.copy2(out / key / name, path)
    files.append({'document': key, 'build_origin': 'build-07', 'path': str(path),
                  'bytes': path.stat().st_size, 'sha256': digest(path)})
receipt = {'started_utc': started, 'completed_utc': datetime.now(timezone.utc).isoformat(),
           'bundle_sha256': args.bundle_sha256, 'driver_sha256': digest(Path(__file__)),
           'parallel_documents': 2, 'passes_per_document': 3,
           'source_unchanged': True, 'base_unchanged': True,
           'change': 'Formal white/blue/teal engineering visuals: 9 exact data/event/boot figures, 13 exact SVG diagrams, 9 retained screenshot groups; literal math corrected. SVG text remains editable, outlined PDFs avoid observed CFF text-map defects. No RTL/simulation/EDA execution.',
           'files': files}
(out / 'build-receipt.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
subprocess.run([sys.executable, '-X', 'utf8', str(root / 'qa/inspect_reports.py'),
                '--compiled-dir', str(delivery), '--logs-dir', str(out),
                '--result-dir', str(out / 'qa'), '--render-dir', str(out / 'qa-render')], check=True)
inspection = json.loads((out / 'qa/pdf-inspection.json').read_text(encoding='utf-8'))
for key, record in inspection['reports'].items():
    assert record['a4_all_pages'] and record['figure_captions_unique'], (key, 'page size or figure captions')
    for field in ('final_log_diagnostics', 'outside_text', 'footer_mismatches', 'placeholder_pages'):
        assert not record[field], (key, field, record[field])
# These are newly measured document results. Actual-page visual inspection and
# final publication remain pending; no previous PASS is copied into this status.
shutil.copy2(out / 'qa/pdf-inspection.json', root / 'qa/pdf-inspection.json')
shutil.copy2(out / 'qa/page-map.json', root / 'figures/page-map.json')
(root / '交付校验.json').write_text(json.dumps({
    'build': 'build-07', 'status': 'AUTOMATED_INSPECTION_COMPLETE_VISUAL_REVIEW_PENDING',
    'inspection': 'qa/pdf-inspection.json', 'reports': inspection['reports'],
    'scope': 'Document build only; no new RTL, EMU, NEMU, performance or EDA validation.'
}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
(root / 'publication-manifest.json').write_text(json.dumps({
    'build': 'build-07', 'status': 'BUILD_CANDIDATE_VISUAL_REVIEW_PENDING',
    'files': files
}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
metadata = out / 'metadata.zip'
with zipfile.ZipFile(metadata, 'w', zipfile.ZIP_DEFLATED) as archive:
    for key in names:
        for ext in ('.log', '.aux', '-pass3.txt'):
            archive.write(out / key / (key + ext), str(PurePosixPath(key) / (key + ext)))
    for name in ('build-receipt.json', 'frozen-sources.json', 'input-delta-manifest.json'):
        archive.write(out / name, name)
    for path in sorted((root / 'figures').glob('*.pdf')):
        archive.write(path, 'source/figures/' + path.name)
    for rel in ('figures/screenshot-layout.json', 'figures/diagram-layout.json',
                'figures/evidence-20261105/generated-figures.json'):
        archive.write(root / rel, 'source/' + rel)
    for path in sorted((out / 'qa').glob('*.json')):
        archive.write(path, 'qa/' + path.name)
files.append({'document': 'metadata', 'path': str(metadata),
              'bytes': metadata.stat().st_size, 'sha256': digest(metadata)})
print(json.dumps({'files': files}, ensure_ascii=False), flush=True)
